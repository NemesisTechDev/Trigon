#!/usr/bin/env python3
"""Regenerates lib/embed/anime_mal_data.dart: the TMDB-show -> MyAnimeList-id table the
VidLink embed server uses for anime (and only anime; movies and other TV use TMDB ids).

Source: the community-maintained Fribb/anime-lists dataset. Re-run from the project root
every month or two so newly released anime resolve:

    python3 tools/build_anime_mal_data.py

Row format per TMDB show id:  [malId, tmdbSeason | null, episodeOffset]
  * Several MAL entries can cover ONE TMDB season (split cours); each MAL entry restarts at
    episode 1, so the app subtracts `episodeOffset` from the TMDB episode number.
  * tmdbSeason == null means MAL keeps the whole show as one long absolute-numbered entry.
"""
import collections, json, os, sys, urllib.request

URL = "https://raw.githubusercontent.com/Fribb/anime-lists/master/anime-list-full.json"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "embed", "anime_mal_data.dart")

def ids(v):  # the dataset uses an int for tv ids and a list for movie ids; accept both
    if isinstance(v, int): return [v]
    if isinstance(v, list): return [x for x in v if isinstance(x, int)]
    return []

src = sys.argv[1] if len(sys.argv) > 1 else None
data = json.load(open(src)) if src else json.load(urllib.request.urlopen(URL, timeout=120))

tv = collections.defaultdict(list)
for e in data:
    t, mal = e.get("themoviedb_id"), e.get("mal_id")
    if not isinstance(t, dict) or not isinstance(mal, int):
        continue
    for tid in ids(t.get("tv")):
        season = (e.get("season") or {}).get("tmdb")
        offset = (e.get("episode_offset") or {}).get("tmdb") or 0
        row = [mal, season, offset]
        if row not in tv[str(tid)]:
            tv[str(tid)].append(row)

lines = []
for k in sorted(tv, key=int):
    rows = sorted(tv[k], key=lambda r: (-1 if r[1] is None else r[1], r[2]))
    lines.append('"%s":%s' % (k, json.dumps(rows, separators=(",", ":"))))
body = '{"tv":{\n' + ",\n".join(lines) + "\n}}"
assert "'''" not in body and "\\" not in body and "$" not in body  # safe inside r'''...'''

with open(OUT, "w", newline="\n") as f:
    f.write("// GENERATED by tools/build_anime_mal_data.py - do not edit by hand.\n")
    f.write("// TMDB show id -> [malId, tmdbSeason|null, episodeOffset] (see anime_mal_map.dart).\n")
    f.write("// Source: Fribb/anime-lists. %d shows.\n" % len(tv))
    f.write("const String kAnimeMalJson = r'''" + body + "''';\n")
print("wrote", os.path.normpath(OUT), "-", len(tv), "shows,", os.path.getsize(OUT), "bytes")
