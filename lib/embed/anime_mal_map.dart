import 'dart:convert';

import '../catalog/catalog_models.dart';
import 'anime_mal_data.dart';

/// One MyAnimeList entry that covers part of a TMDB show.
class _MalRow {
  const _MalRow(this.malId, this.season, this.offset);

  final int malId;

  /// TMDB season this entry belongs to. Null: MAL keeps the whole show as one
  /// long entry with absolute episode numbers (One Piece, Detective Conan...).
  final int? season;

  /// How many of that TMDB season's episodes come BEFORE this entry (a TMDB
  /// season can be split across several MAL entries, each restarting at 1).
  final int offset;
}

/// The MyAnimeList id and the episode number to ask VidLink for.
class AnimeMalMatch {
  const AnimeMalMatch(this.malId, this.number);

  final int malId;
  final int number;

  @override
  String toString() => 'AnimeMalMatch(mal: $malId, number: $number)';
}

/// TMDB -> MyAnimeList lookup. Used ONLY by the VidLink embed server, and only
/// for anime series: VidLink's anime URL is keyed by MAL id, while movies and
/// every other show keep using their TMDB id.
///
/// The table (anime_mal_data.dart) is generated by
/// tools/build_anime_mal_data.py. It is parsed once, on first use.
class AnimeMalMap {
  AnimeMalMap._();

  /// TMDB's "Animation" genre.
  static const int _animationGenre = 16;

  /// Original languages treated as anime. Add 'zh' / 'ko' here if donghua /
  /// manhwa adaptations should use MAL ids too.
  static const Set<String> _languages = {'ja'};

  static Map<int, List<_MalRow>>? _tv;

  static Map<int, List<_MalRow>> get _table {
    final cached = _tv;
    if (cached != null) return cached;
    final root = jsonDecode(kAnimeMalJson) as Map<String, dynamic>;
    final out = <int, List<_MalRow>>{};
    (root['tv'] as Map<String, dynamic>).forEach((key, value) {
      final id = int.tryParse(key);
      if (id == null || value is! List) return;
      final rows = <_MalRow>[];
      for (final r in value) {
        if (r is! List || r.length < 3) continue;
        rows.add(_MalRow(
          (r[0] as num).toInt(),
          (r[1] as num?)?.toInt(),
          (r[2] as num).toInt(),
        ));
      }
      if (rows.isNotEmpty) out[id] = rows;
    });
    return _tv = out;
  }

  /// True if the table has this TMDB show at all (a cheap, offline check).
  static bool contains(int tmdbId) => _table.containsKey(tmdbId);

  /// TMDB has no "anime" flag, so: Animation genre + a Japanese original
  /// language. Needs the genre ids and original language that TMDB returns on
  /// list and detail calls (not the slimmed-down saved snapshots).
  static bool isAnime(CatalogTitle t) =>
      t.type == CatalogType.series &&
      t.genreIds.contains(_animationGenre) &&
      _languages.contains(t.originalLanguage);

  /// True when this show is kept by MAL as one absolute-numbered entry, so the
  /// caller must supply [resolve]'s `absoluteEpisode`.
  static bool needsAbsolute(int tmdbId) =>
      _table[tmdbId]?.any((r) => r.season == null) ?? false;

  /// Absolute episode number of [season] x [episode]: the episodes of every
  /// earlier regular season, plus [episode]. Null if [seasons] is empty.
  static int? absoluteEpisode(
    List<CatalogSeason> seasons,
    int season,
    int episode,
  ) {
    if (seasons.isEmpty) return null;
    var n = 0;
    for (final s in seasons) {
      if (s.number > 0 && s.number < season) n += s.episodeCount;
    }
    return n + episode;
  }

  /// Which MAL entry (and which episode of it) TMDB [season] x [episode] is.
  /// Null when the show is unknown or can't be placed; callers then fall back
  /// to the normal TMDB URL.
  static AnimeMalMatch? resolve(
    int tmdbId,
    int season,
    int episode, {
    int? absoluteEpisode,
  }) {
    final rows = _table[tmdbId];
    if (rows == null || rows.isEmpty || episode < 1) return null;

    // The entry for this season whose first episode is the latest one still
    // at or before the requested episode.
    AnimeMalMatch? pick(Iterable<_MalRow> candidates, int ep) {
      _MalRow? best;
      for (final r in candidates) {
        if (r.offset <= ep - 1 && (best == null || r.offset > best.offset)) {
          best = r;
        }
      }
      return best == null ? null : AnimeMalMatch(best.malId, ep - best.offset);
    }

    final seasonal = rows.where((r) => r.season == season);
    final hit = pick(seasonal, episode);
    if (hit != null) return hit;

    final absolute = rows.where((r) => r.season == null);
    if (absolute.isNotEmpty && absoluteEpisode != null && absoluteEpisode >= 1) {
      return pick(absolute, absoluteEpisode);
    }
    return null;
  }
}
