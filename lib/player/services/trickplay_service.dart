/// Cache-Control sent on every trickplay network fetch (tile images and,
/// via the same header value at each `getItem`-refresh call site, the
/// item metadata that carries the Trickplay map). Belt-and-suspenders
/// alongside the `tc`/`iv` URL-versioning below: that trick only busts
/// *this app's own* on-device disk cache, which is all client code can
/// normally see — it can't do anything about a transparent proxy,
/// mobile-carrier data-saver, or CDN sitting on the path to the server
/// and serving an old cached copy of the same URL back to every client
/// regardless of what query string was requested. Explicitly asking
/// every hop not to cache is the only lever this app has over that
/// layer; a well-behaved intermediary honors it; a misbehaving one at
/// least isn't made worse by sending it.
const Map<String, String> kTrickplayNoCacheHeaders = {
  'Cache-Control': 'no-cache, no-store',
  'Pragma': 'no-cache',
};

/// One resolved trickplay "quality" for a given media source — mirrors
/// the shape of a single entry inside Jellyfin's
/// `Trickplay[mediaSourceId][width]` dictionary, plus the mediaSourceId
/// it came from (needed to build the tile image URL).
class TrickplayResolution {
  final String mediaSourceId;
  final int width;
  final int height;
  final int tileWidth;
  final int tileHeight;
  final int thumbnailCount;
  final int intervalMs;

  const TrickplayResolution({
    required this.mediaSourceId,
    required this.width,
    required this.height,
    required this.tileWidth,
    required this.tileHeight,
    required this.thumbnailCount,
    required this.intervalMs,
  });

  /// How many individual thumbnails fit on one sprite-sheet image.
  int get thumbsPerSheet => tileWidth * tileHeight;
}

/// Where a given playback [Duration] lands within a trickplay grid: which
/// sprite-sheet ("tile") image to fetch, and which row/column inside that
/// sheet holds the thumbnail for that moment.
class TrickplayFrame {
  final int tileIndex;
  final int row;
  final int col;

  const TrickplayFrame({
    required this.tileIndex,
    required this.row,
    required this.col,
  });
}

class TrickplayService {
  TrickplayService._();

  /// Picks the best available trickplay resolution for [item], preferring
  /// the media source that's actually playing (matching mpv's opened
  /// source — same fallback-to-item-id convention used everywhere else
  /// in the player for single-source items, see PlayerManager._syncTracks)
  /// and, within that, whichever configured tile width actually has the
  /// most complete data, tie-broken toward the smallest width for
  /// bandwidth (see the completeness comment further down for why this
  /// can't just always take the smallest width). Returns null when the
  /// server has no trickplay data for this item at all (older libraries,
  /// or scanning still in progress).
  static TrickplayResolution? resolve(MediaItem item) {
    final trickplay = item.trickplay;
    if (trickplay == null || trickplay.isEmpty) return null;

    final preferredSourceId = (item.mediaSources != null &&
        item.mediaSources!.isNotEmpty)
        ? item.mediaSources!.first["Id"]?.toString() ?? item.id
        : item.id;

    Map<String, dynamic>? widths;
    String sourceId;

    if (trickplay[preferredSourceId] is Map) {
      widths = Map<String, dynamic>.from(trickplay[preferredSourceId]);
      sourceId = preferredSourceId;
    } else {
      // Fall back to whatever the first (and, for the vast majority of
      // items, only) media source key actually is, rather than giving
      // up — a mismatched id shouldn't mean no preview at all.
      final firstKey = trickplay.keys.first;
      final firstValue = trickplay[firstKey];
      if (firstValue is! Map) return null;

      widths = Map<String, dynamic>.from(firstValue);
      sourceId = firstKey;
    }

    if (widths.isEmpty) return null;

    // Widths are string keys ("320", "640", ...), each generated by
    // Jellyfin as its OWN independent background job — the server can
    // (and, per confirmed reports like jellyfin/jellyfin#17464 and the
    // wider "trickplay generation stalls/fails per file" pattern, does)
    // finish one configured width's job while another is still
    // mid-generation or never completed at all, for the exact same
    // item. Each width's own ThumbnailCount reflects how much of ITS
    // OWN job actually finished, so ThumbnailCount is the one reliable
    // signal for "is this particular width's data actually complete",
    // not just "does this width exist in the map at all".
    //
    // This used to just take the numerically smallest width
    // unconditionally, on the reasoning that the scrub preview is only
    // ever shown at ~160-200px wide, so a smaller sheet is already
    // sharp enough and cheaper to fetch/decode. That reasoning still
    // holds AMONG equally-complete widths — but taking the smallest
    // width with no regard for completeness meant a title whose
    // smallest configured width happened to be the one still stuck
    // mid-job got that job's tiny, stale ThumbnailCount handed to
    // `frameFor`, which then clamps almost every scrub position past
    // that small count down to the same last available tile — reading
    // exactly like "the whole seek bar is stuck on one image", even
    // though a fully-generated LARGER width was sitting right there in
    // the same map the whole time. Jellyfin's own web client isn't
    // fooled by this because it resolves per-width completeness the
    // same way, which is why the same title scrubs correctly there.
    //
    // So: pick the width with the highest ThumbnailCount first (most
    // complete data wins, regardless of pixel size), and only fall back
    // to preferring the smaller pixel width as a tie-breaker once two
    // candidates are equally complete — which is the normal, healthy
    // case for the vast majority of titles and keeps the original
    // bandwidth optimization exactly as before for them.
    int? bestWidth;
    int? bestHeight;
    int? bestTileWidth;
    int? bestTileHeight;
    int? bestThumbnailCount;
    int? bestIntervalMs;

    for (final key in widths.keys) {
      final info = widths[key];
      if (info is! Map) continue;

      final width =
          (info["Width"] as num?)?.toInt() ?? int.tryParse(key) ?? 0;
      final height = (info["Height"] as num?)?.toInt() ?? 0;
      final tileWidth = (info["TileWidth"] as num?)?.toInt() ?? 1;
      final tileHeight = (info["TileHeight"] as num?)?.toInt() ?? 1;
      final thumbnailCount = (info["ThumbnailCount"] as num?)?.toInt() ?? 0;
      final intervalMs = (info["Interval"] as num?)?.toInt() ?? 10000;

      if (width <= 0 || height <= 0 || thumbnailCount <= 0) continue;

      final isMoreComplete = bestThumbnailCount == null ||
          thumbnailCount > bestThumbnailCount;
      final isEquallyCompleteButSmaller = bestThumbnailCount != null &&
          thumbnailCount == bestThumbnailCount &&
          (bestWidth == null || width < bestWidth);

      if (isMoreComplete || isEquallyCompleteButSmaller) {
        bestWidth = width;
        bestHeight = height;
        bestTileWidth = tileWidth;
        bestTileHeight = tileHeight;
        bestThumbnailCount = thumbnailCount;
        bestIntervalMs = intervalMs;
      }
    }

    if (bestWidth == null ||
        bestHeight == null ||
        bestThumbnailCount == null) {
      return null;
    }

    return TrickplayResolution(
      mediaSourceId: sourceId,
      width: bestWidth,
      height: bestHeight,
      tileWidth: bestTileWidth ?? 1,
      tileHeight: bestTileHeight ?? 1,
      thumbnailCount: bestThumbnailCount,
      intervalMs: bestIntervalMs ?? 10000,
    );
  }

  /// Sanity-checks an already-loaded `item.trickplay` against the item's
  /// own Jellyfin-reported runtime, so a snapshot fetched while server-
  /// side trickplay generation was still incomplete for this title isn't
  /// treated as "done" for the rest of playback.
  ///
  /// PULLED OUT OF PlayerManager (SEEK-THUMBNAIL FIX, part 2): this used
  /// to be a private method on PlayerManager, called only from that
  /// class's own `_augmentWithPlaybackFields`. CastManager's parallel
  /// `_ensureFullMediaItem` — which exists for exactly the same reason,
  /// to backfill mediaStreams/mediaSources/trickplay onto an item right
  /// as it actually starts playing/casting — had no way to reach a
  /// PlayerManager-private method from a different file, so it fell back
  /// to a *weaker* check of its own: "does `mediaStreams` already have
  /// something in it", with no regard for whether the trickplay data
  /// specifically was actually complete. A movie cast straight from its
  /// details screen always has `mediaStreams` populated (that screen
  /// fetches full fields up front) — so `_ensureFullMediaItem` treated
  /// it as fully done and never re-fetched, even when the Trickplay
  /// portion of that same snapshot was taken while generation was still
  /// running and never got refreshed for the rest of that cast session.
  /// That's what made scrubbing a *cast* movie look "stuck on one image"
  /// even though `PlayerManager`'s equivalent local-playback path was
  /// already immune to it. Making this a shared, public utility both
  /// call is what closes that gap for good instead of requiring every
  /// future playback path to remember to reimplement it correctly.
  ///
  /// Deliberately coarse rather than exact: real trickplay tracks always
  /// fall a little short of the precise runtime (the last thumbnail
  /// covers up to the last full sampling interval before the end, not
  /// whatever odd fraction of a second remains after it), so this only
  /// flags genuinely incomplete data — missing a large, unambiguous
  /// chunk of the runtime — rather than false-flagging a normal, fully-
  /// generated track over the last few seconds of rounding.
  static bool looksComplete(MediaItem item) {
    final res = resolve(item);
    if (res == null) return false;

    final runtimeMs = item.runtime.inMilliseconds;
    // No runtime to sanity-check against (shouldn't normally happen by
    // the time something's about to play) — nothing more this check can
    // tell us, so don't force an extra fetch on the strength of it alone.
    if (runtimeMs <= 0) return true;

    final coveredMs = res.thumbnailCount * res.intervalMs;
    return coveredMs >= runtimeMs * 0.9;
  }

  /// Resolves a playback [position] to the specific sprite-sheet tile and
  /// grid cell within it that holds the closest thumbnail.
  ///
  /// SEEK-THUMBNAIL FIX (part 5 — stop trusting `thumbnailCount` as a
  /// hard ceiling): this used to clamp `thumbIndex` to
  /// `res.thumbnailCount - 1`, on the assumption that Jellyfin's
  /// reported `ThumbnailCount` for a width is an accurate account of how
  /// many real tiles exist for it. Disproven by a real report: "Fury"
  /// reported `ThumbnailCount: 9` from this app on every fresh,
  /// genuinely-uncached refetch (confirmed — a per-call cache-busting
  /// query param made no difference), while both Jellyfin's own web
  /// client AND a third-party client (Moonfin), hitting the exact same
  /// server over the exact same network path, scrubbed the same file's
  /// thumbnails correctly the entire way through. Same backend, same
  /// network hop, three different clients, two different pictures of
  /// how much trickplay data exists — the two that work don't take the
  /// server's reported count as gospel and just request the tile that
  /// *should* exist for a given position/interval, trusting the file
  /// server (a 200 vs. a 404) to say whether it's really there instead
  /// of trusting a metadata field a step removed from the actual tiles
  /// on disk. This matches a known class of Jellyfin bug (see the
  /// `jellyfin/jellyfin#17464`-style reports cited on [resolve]):
  /// generation writes tiles to disk as it goes, but the count Jellyfin
  /// hands back in the Item response can lag behind what's actually
  /// been written, or never get corrected after the fact.
  ///
  /// So this no longer refuses to compute an index past
  /// `thumbnailCount` — it only floors at zero. A position past what's
  /// actually been generated (whether that's because `thumbnailCount`
  /// under-reported reality, or because it was accurate all along and
  /// there genuinely isn't a tile there yet) now resolves to whatever
  /// tile *would* hold that moment, and asking the server for it is what
  /// actually finds out which case this is — a real 404 for a truly
  /// absent tile, or a real 200 for one `thumbnailCount` didn't know
  /// about. [TrickplayPreview] is what acts on that answer: it hides
  /// itself the first time a requested tile genuinely fails to load,
  /// instead of this method silently substituting the last known-good
  /// tile as a stand-in for a position it was never actually generated
  /// for.
  static TrickplayFrame frameFor(
      TrickplayResolution res,
      Duration position,
      ) {
    final interval = res.intervalMs <= 0 ? 10000 : res.intervalMs;

    final thumbIndex =
        (position.inMilliseconds / interval).floor().clamp(0, 1 << 30);

    final perSheet = res.thumbsPerSheet <= 0 ? 1 : res.thumbsPerSheet;

    final tileIndex = thumbIndex ~/ perSheet;
    final localIndex = thumbIndex % perSheet;

    final tileWidth = res.tileWidth <= 0 ? 1 : res.tileWidth;
    final row = localIndex ~/ tileWidth;
    final col = localIndex % tileWidth;

    return TrickplayFrame(tileIndex: tileIndex, row: row, col: col);
  }


  /// URL of the sprite-sheet jpg containing thumbnail [tileIndex] at the
  /// given resolution — one HTTP request covers up to `TileWidth *
  /// TileHeight` thumbnails, which is what keeps scrubbing smooth instead
  /// of firing a request per frame.
  ///
  /// `tc`/`iv` (the resolution's thumbnailCount/intervalMs) are tacked on
  /// as otherwise-inert query params purely to make the URL — and
  /// therefore the cache key `CachedNetworkImage`/`NemesisImageCache`
  /// key their 60-day disk cache on — change whenever the server's
  /// trickplay data for this item changes. Root cause of "stuck on one
  /// frame the whole scrub, only for some titles": Jellyfin generates
  /// trickplay tiles as a background job and, per confirmed upstream
  /// bugs (e.g. jellyfin/jellyfin#17464), can leave an item with only a
  /// handful of tiles covering the first few minutes while still
  /// reporting success — if this app's seek bar was scrubbed on a title
  /// while its generation was incomplete (or before a later re-scan
  /// completed it), the incomplete tile(s) fetched at that moment got
  /// written to this device's disk cache under this same URL forever,
  /// since nothing about the URL changed once generation actually
  /// finished. `frameFor`'s clamp to `thumbnailCount - 1` then keeps
  /// resolving to that one already-cached (stale) tile for the entire
  /// back half of the runtime, no matter how much real data the server
  /// now has — a plain network re-fetch was never triggered because
  /// nothing invalidated the old cache entry. The web client isn't
  /// hitting this because a browser's cache for the same URL gets
  /// cleared/expires on a totally different, much shorter cycle than
  /// this app's dedicated 60-day image cache. Folding thumbnailCount/
  /// interval into the URL means a completed (re)generation — which
  /// necessarily changes at least one of those — naturally mints a new
  /// cache key instead of resolving to the old stale entry.
  static String tileImageUrl(
      String itemId,
      TrickplayResolution res,
      int tileIndex,
      ) {
    return "${JellyfinClient.serverUrl}"
        "/Videos/$itemId/Trickplay/${res.width}/$tileIndex.jpg"
        "?api_key=${JellyfinClient.token}"
        "&MediaSourceId=${res.mediaSourceId}"
        "&tc=${res.thumbnailCount}"
        "&iv=${res.intervalMs}";
  }

  /// Warms the shared `CachedNetworkImage` memory/disk cache with every
  /// sprite-sheet tile a given resolution has, up front — as soon as
  /// playback starts, well before the user ever touches the seek bar —
  /// instead of leaving each tile to be fetched and decoded live, for
  /// the first time, in the middle of a drag. A movie-length item is
  /// typically only a handful of sheets (e.g. ~10s interval over 2
  /// hours at 100 thumbs/sheet is well under 10 tiles), so downloading
  /// all of them costs little, and it's what turns "first time you drag
  /// over a new spot" from a visible network+decode stall into an
  /// instant cache hit.
  ///
  /// SEEK-THUMBNAIL FIX (part 6 — precache at the size that's actually
  /// requested): this used to `precacheImage` a bare
  /// `CachedNetworkImageProvider`, with no resize target. That warms the
  /// *disk* cache (so no network refetch happens later) but NOT the
  /// in-memory decoded-image cache `TrickplayPreview` actually reads
  /// from — `CachedNetworkImage`'s `memCacheWidth`/`memCacheHeight`
  /// wrap the provider in a `ResizeImage`, and Flutter's `ImageCache`
  /// keys on the *exact* resolved provider (base provider + resize
  /// target), not just the URL. A precache with no resize target and a
  /// live request wrapped in `ResizeImage(width: ..., height: ...)` are
  /// two different cache keys pointing at the same bytes — so despite
  /// every tile already sitting on disk, every single drag still paid
  /// for a full decode-and-downscale of the raw sprite sheet (a
  /// multi-megapixel JPEG for a 10×10 grid) live, in the middle of the
  /// gesture, which is exactly the noticeable dark-placeholder pause
  /// this was supposed to prevent in the first place.
  ///
  /// `[previewWidth]`/`[previewHeight]` must match what `TrickplayPreview`
  /// is actually built with (both seek bars use the same 160×90 this
  /// defaults to) — mismatched values here just warms the wrong resize
  /// key all over again.
  static Future<void> prefetchAll(
      BuildContext context,
      String itemId,
      TrickplayResolution res, {
        Duration? priorityPosition,
        double previewWidth = 160,
        double previewHeight = 90,
      }) async {
    final perSheet = res.thumbsPerSheet <= 0 ? 1 : res.thumbsPerSheet;
    final tileCount = (res.thumbnailCount / perSheet).ceil();

    if (tileCount <= 0) return;

    // Same formula TrickplayPreview uses for memCacheWidth/memCacheHeight
    // — this has to match exactly, or the ResizeImage wrapper below
    // produces a cache key the live widget never looks up.
    final devicePixelRatio = MediaQuery.devicePixelRatioOf(context);
    final memCacheWidth =
        (res.tileWidth * previewWidth * devicePixelRatio).round();
    final memCacheHeight =
        (res.tileHeight * previewHeight * devicePixelRatio).round();

    // `ResizeImage.resizeIfNeeded` (not a plain `ResizeImage(...)`) is
    // the exact static helper the image pipeline itself uses to decide
    // whether/how to wrap a provider for a target size — using anything
    // else here risks subtly different default parameters producing a
    // subtly different key than `CachedNetworkImage`'s own internal
    // wrapping does, silently reintroducing this same mismatch.
    ImageProvider providerFor(String url) => ResizeImage.resizeIfNeeded(
      memCacheWidth,
      memCacheHeight,
      CachedNetworkImageProvider(
        url,
        cacheManager: NemesisImageCache.instance,
        headers: kTrickplayNoCacheHeaders,
      ),
    );

    int? priorityTile;

    if (priorityPosition != null) {
      priorityTile = frameFor(res, priorityPosition)
          .tileIndex
          .clamp(0, tileCount - 1);

      if (!context.mounted) return;

      await precacheImage(
        providerFor(tileImageUrl(itemId, res, priorityTile)),
        context,
      );
    }

    for (var i = 0; i < tileCount; i++) {
      if (i == priorityTile) continue;
      if (!context.mounted) return;

      final url = tileImageUrl(itemId, res, i);
      // Fire-and-forget: each of these lands in the same ImageCache
      // that CachedNetworkImage/TrickplayPreview reads from, keyed on
      // the same url AND the same resize target, so a later
      // CachedNetworkImage(imageUrl: url, memCacheWidth: ...,
      // memCacheHeight: ...) resolves an already-decoded image instead
      // of re-triggering a decode. Must use the same `cacheManager` as
      // TrickplayPreview (NemesisImageCache, not cached_network_image's
      // default) — otherwise this warms a disk cache TrickplayPreview
      // never reads from, and every tile still has to be fetched live
      // the first time it's scrubbed to, no matter how far ahead of
      // time this ran.
      precacheImage(
        providerFor(url),
        context,
      );
    }
  }
}